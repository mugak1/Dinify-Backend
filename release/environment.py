"""THE ENVIRONMENT — acquiring exactly the locked files, building a fresh interpreter
environment from ONLY those files, and proving afterwards that what is installed is what
was admitted.

ACQUISITION (network, the only step that is). Each locked file is fetched from the exact
``files.pythonhosted.org`` address the lock names and admitted only if its size and
SHA-256 are the lock's. There is no resolution and no index query: nothing is chosen at
certification time, so a new release, a new wheel for an old version or a changed index
cannot change what is certified. A wheelhouse holding anything but the locked files is
refused.

INSTALLATION (offline). ``python -m venv --without-pip`` — no bundled installer — then the
pinned pip wheel, verified first, installs ITSELF into the environment, and that pip
installs the application closure with ``--isolated --no-index --no-cache-dir
--find-links <wheelhouse> --require-hashes --no-deps --only-binary=:all:``: no index, no
cache, no configuration file or ``PIP_*`` variable, no dependency resolution, no source
build. A file missing from the wheelhouse fails the install; it is never fetched.

RECONCILIATION (offline). The probe, run by the environment's own interpreter, reports
every installed distribution with its RECORD. The installed set must be exactly the locked
set; every Requires-Dist edge, with markers evaluated by that interpreter, must be
satisfied and the closure reachable from the direct inputs must be exactly the locked
application packages (so a locked package the target does not need — a Windows-only
dependency, say — is refused, not silently kept); every file the wheel ships into
site-packages must be on disk with the wheel's own RECORD hash (after the wheel's RECORD is
checked against the wheel's own bytes); nothing else may sit in site-packages unowned;
and ``pip check`` must pass. The result is a PORTABLE inventory — names, versions, wheel
hashes and the digests of the installed files — which does not depend on where the
environment lives, so the certified environment and a reconstruction can be compared.

Console scripts in ``bin/`` are generated by pip with the environment's own path in their
first line, so they are counted and NOT compared; nothing in this closure is executed
through them.
"""

